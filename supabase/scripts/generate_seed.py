"""Generate supabase/seed.sql from data/instruments.csv and engine/config.py, and
web/src/content/gameConfig.generated.ts from engine/config.py (rule values for pages that
cannot read the game_config table, e.g. the public rules page).

Usage (from the repository root):
    python supabase/scripts/generate_seed.py          # write both files
    python supabase/scripts/generate_seed.py --check  # exit 1 if a file is stale
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

from engine.config import GAME_CONFIG

REPO_ROOT = Path(__file__).resolve().parents[2]
CSV_PATH = REPO_ROOT / "data" / "instruments.csv"
SEED_PATH = REPO_ROOT / "supabase" / "seed.sql"
TS_PATH = REPO_ROOT / "web" / "src" / "content" / "gameConfig.generated.ts"
COLUMNS = ("ticker", "name", "region", "calendar_mic", "currency", "sector")


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_seed() -> str:
    with CSV_PATH.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))

    lines = [
        "-- GENERATED by supabase/scripts/generate_seed.py. Do not edit by hand.",
        "-- Sources: data/instruments.csv and engine/config.py (GAME_CONFIG).",
        "",
        "insert into public.instruments (ticker, name, region, calendar_mic, currency, sector)",
        "values",
    ]
    values = [
        "  (" + ", ".join(sql_literal(row[column]) for column in COLUMNS) + ")" for row in rows
    ]
    lines.append(",\n".join(values))
    lines += [
        "on conflict (ticker) do update set",
        "  name = excluded.name,",
        "  region = excluded.region,",
        "  calendar_mic = excluded.calendar_mic,",
        "  currency = excluded.currency,",
        "  sector = excluded.sector;",
        "",
        "insert into public.game_config (key, value)",
        "values",
    ]
    config_values = [
        f"  ({sql_literal(key)}, {sql_literal(json.dumps(value, sort_keys=True))}::jsonb)"
        for key, value in sorted(GAME_CONFIG.items())
    ]
    lines.append(",\n".join(config_values))
    lines += [
        "on conflict (key) do update set value = excluded.value;",
        "",
        "delete from public.game_config",
        "where key not in (" + ", ".join(sql_literal(key) for key in sorted(GAME_CONFIG)) + ");",
        "",
    ]
    return "\n".join(lines)


def render_ts() -> str:
    body = json.dumps(GAME_CONFIG, indent=2, sort_keys=True, ensure_ascii=False)
    return (
        "// GENERATED by supabase/scripts/generate_seed.py from engine/config.py.\n"
        "// Do not edit by hand. The same values are in the game_config table.\n"
        f"export const GAME_CONFIG_VALUES = {body} as const\n"
    )


def main(argv: list[str]) -> int:
    outputs = {SEED_PATH: render_seed(), TS_PATH: render_ts()}
    if "--check" in argv:
        stale = [
            path
            for path, content in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        for path in stale:
            name = path.relative_to(REPO_ROOT)
            print(f"{name} is stale: run python supabase/scripts/generate_seed.py")
        if stale:
            return 1
        print("supabase/seed.sql and web/src/content/gameConfig.generated.ts are up to date")
        return 0
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
